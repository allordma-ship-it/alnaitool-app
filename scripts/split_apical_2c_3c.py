#!/usr/bin/env python3
"""
EchoScope – one-off migration: split the combined "apical_2c_3c" view into two standard views,
"apical_2c" (apical 2-chamber) and "apical_3c" (apical 3-chamber / apical long axis).

Copies the shared fields of apical_2c_3c, gives each view its own title, probe text, notch,
key structures, reference values and checklist, and removes the combined view. Steps, console
content, loops, overlays, schemas, orientation and galleries are then regenerated by the
pipeline scripts, which now know both ids:

  python3 scripts/split_apical_2c_3c.py
  python3 scripts/convert_real_loops.py        # A2C and A3C get their own real loop
  python3 scripts/guided_steps.py && python3 scripts/console_timing_content.py
  python3 scripts/measurement_overlays.py && python3 scripts/integrate_echocardiographer.py
  python3 scripts/valve_content.py && python3 scripts/gen_schema_svg.py && python3 scripts/gen_orientation_svg.py
"""

from __future__ import annotations

import copy
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DB = os.path.join(ROOT, "app", "src", "main", "assets", "echo_protocol_full.json")


def t(en, de, ar):
    return {"en": en, "de": de, "ar": ar}


def main():
    with open(DB, encoding="utf-8") as f:
        db = json.load(f)
    window = next(w for w in db["windows"] if any(v["id"] == "apical_2c_3c" for v in w["views"]))
    index = next(i for i, v in enumerate(window["views"]) if v["id"] == "apical_2c_3c")
    old = window["views"][index]
    ref = {m["parameter"]["en"]: m for m in old["referenceMeasurements"]["adult"]}

    a2c = copy.deepcopy(old)
    a2c.update({
        "id": "apical_2c",
        "title": t("Apical 2-Chamber", "Apikaler Zweikammerblick", "المقطع القمي ثنائي الحجرات"),
        "probePosition": t(
            "From the A4C rotate the probe about 60° counter-clockwise until the RV disappears completely.",
            "Aus dem 4K-Blick den Schallkopf etwa 60° gegen den Uhrzeigersinn drehen, bis der RV vollständig verschwindet.",
            "من المقطع رباعي الحجرات دوّر المسبار نحو 60° عكس عقارب الساعة حتى يختفي البطين الأيمن تماماً."),
        "notchClock": "12–1",
        "notchHours": [12.5],
        "notchDescription": t("Notch at 12–1 o'clock.", "Markierung bei 12–1 Uhr.", "العلامة عند الساعة 12–1."),
        "videoAsset": "loops/apical_2c.mp4",
        "svgAsset": "svg/apical_2c.svg",
        "keyStructures": [
            t("LV with inferior wall (left of image) and anterior wall (right)",
              "LV mit inferiorer Wand (links im Bild) und Vorderwand (rechts)",
              "البطين الأيسر مع الجدار السفلي (يسار الصورة) والأمامي (يمينها)"),
            t("Left atrium and left atrial appendage", "Linker Vorhof und linkes Vorhofohr", "الأذين الأيسر وزائدته"),
            t("Mitral valve (P1 / A2 / P3 scallops)", "Mitralklappe (Segmente P1 / A2 / P3)", "الصمام التاجي (القطع P1 / A2 / P3)"),
        ],
        "referenceMeasurements": {
            "adult": [m for k, m in ref.items() if "LVEF" in k or "LA" in k or "Simpson" in k] or old["referenceMeasurements"]["adult"],
            "pediatric": old["referenceMeasurements"]["pediatric"],
        },
        "checklist": [
            t("Rotate counter-clockwise until the RV disappears", "Gegen den Uhrzeigersinn drehen, bis der RV verschwindet",
              "التدوير عكس عقارب الساعة حتى يختفي البطين الأيمن"),
            t("Apex not foreshortened (LV length within 10 % of A4C)", "Apex nicht verkürzt (LV-Länge ±10 % zum 4K-Blick)",
              "القمة غير مقصّرة (طول البطين ضمن 10 % من الرباعي)"),
            t("Assess anterior and inferior walls", "Vorder- und Hinterwand (inferior) beurteilen", "تقييم الجدارين الأمامي والسفلي"),
            t("Trace ED and ES endocardium for the biplane EF", "Endokard in ED und ES für die biplane EF umfahren",
              "تتبّع الشغاف في نهاية الانبساط والانقباض للكسر القذفي ثنائي المستوى"),
            t("LA volume at end-systole (biplane with A4C)", "LA-Volumen endsystolisch (biplan mit 4K)",
              "حجم الأذين الأيسر في نهاية الانقباض (ثنائي المستوى مع الرباعي)"),
        ],
    })

    a3c = copy.deepcopy(old)
    a3c.update({
        "id": "apical_3c",
        "title": t("Apical 3-Chamber (Apical Long Axis)", "Apikaler Dreikammerblick (apikale lange Achse)",
                   "المقطع القمي ثلاثي الحجرات (المحور الطويل القمي)"),
        "probePosition": t(
            "From the A2C keep rotating counter-clockwise (about 120° from A4C) until the LVOT, aortic valve and aorta appear.",
            "Aus dem 2K-Blick weiter gegen den Uhrzeigersinn drehen (etwa 120° vom 4K-Blick), bis LVOT, Aortenklappe und Aorta erscheinen.",
            "من المقطع ثنائي الحجرات تابع التدوير عكس عقارب الساعة (نحو 120° من الرباعي) حتى يظهر مخرج البطين الأيسر والصمام الأبهري والأبهر."),
        "notchClock": "10–11",
        "notchHours": [10.5],
        "notchDescription": t("Notch at 10–11 o'clock.", "Markierung bei 10–11 Uhr.", "العلامة عند الساعة 10–11."),
        "videoAsset": "loops/apical_3c.mp4",
        "svgAsset": "svg/apical_3c.svg",
        "keyStructures": [
            t("LV with inferolateral wall (left of image) and anteroseptal wall (right)",
              "LV mit inferolateraler Wand (links im Bild) und anteroseptaler Wand (rechts)",
              "البطين الأيسر مع الجدار السفلي الجانبي (يسار الصورة) والأمامي الحاجزي (يمينها)"),
            t("LVOT, aortic valve and aortic root", "LVOT, Aortenklappe und Aortenwurzel", "مخرج البطين الأيسر والصمام الأبهري وجذر الأبهر"),
            t("Left atrium and mitral valve (A2 / P2)", "Linker Vorhof und Mitralklappe (A2 / P2)", "الأذين الأيسر والصمام التاجي (A2 / P2)"),
        ],
        "referenceMeasurements": {
            "adult": [m for k, m in ref.items() if "GLS" in k or "strain" in k.lower()] or old["referenceMeasurements"]["adult"],
            "pediatric": old["referenceMeasurements"]["pediatric"],
        },
        "checklist": [
            t("Rotate further until LVOT and aorta appear", "Weiter drehen, bis LVOT und Aorta erscheinen",
              "متابعة التدوير حتى يظهر مخرج البطين الأيسر والأبهر"),
            t("Assess anteroseptal and inferolateral walls", "Anteroseptale und inferolaterale Wand beurteilen",
              "تقييم الجدارين الأمامي الحاجزي والسفلي الجانبي"),
            t("Colour Doppler over mitral and aortic valve", "Farbdoppler über Mitral- und Aortenklappe",
              "الدوبلر الملوّن فوق الصمامين التاجي والأبهري"),
            t("CW through the aortic valve (alternative to A5C)", "CW durch die Aortenklappe (Alternative zum 5K-Blick)",
              "دوبلر مستمر عبر الصمام الأبهري (بديل عن الخماسي)"),
            t("Store at a high frame rate for strain (GLS)", "Mit hoher Bildrate für Strain (GLS) speichern",
              "احفظ بمعدل إطارات عالٍ لتحليل الإجهاد (GLS)"),
        ],
    })
    for v in (a2c, a3c):
        for key in ("probeGallery", "atlasGallery", "schemaAsset", "schemaCrop", "schemaAspect", "orientationAsset", "steps"):
            v.pop(key, None)
    window["views"][index:index + 1] = [a2c, a3c]
    with open(DB, "w", encoding="utf-8") as f:
        json.dump(db, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("split apical_2c_3c -> apical_2c, apical_3c")


if __name__ == "__main__":
    main()
