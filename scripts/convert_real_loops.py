#!/usr/bin/env python3
"""
EchoScope – convert verified real echo clips (temp_real/) into the app's cine-loop assets.

For every view in MAPPING the listed Wikimedia Commons clips are scaled to 720 px width and
encoded as H.264 (CRF 24, yuv420p, no audio, +faststart) WITHOUT cropping the ultrasound
sector; several clips are joined in order. The script then updates the view in
echo_protocol_full.json:

  * "videoSource": type "real" with title, author, licence and source URL for attribution
  * "ecg":         R-wave times of the loop. The ECHOpedia loops are R-wave-triggered and
                   contain a whole number of beats (checked visually: largest LV cavity on
                   frame 0); end-systole is estimated per beat with QT ≈ 0.39 · √RR.

Views not in MAPPING keep their simulated loop (scripts/simulate_loops.py).

Usage: python3 scripts/convert_real_loops.py
"""

from __future__ import annotations

import json
import math
import os
import re
import subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TEMP = os.path.join(ROOT, "temp_real")
LOOPS = os.path.join(ROOT, "app", "src", "main", "assets", "loops")
DB = os.path.join(ROOT, "app", "src", "main", "assets", "echo_protocol_full.json")

# view id -> list of (Commons title, number of whole beats in that clip)
MAPPING: dict[str, list[tuple[str, int]]] = {
    "psax_papillary": [("File:SAXPAP normal (CardioNetworks ECHOpedia).webm", 3)],
    "apical_2c_3c": [
        ("File:A2Cnormal (CardioNetworks ECGpedia).avi.webm", 3),
        ("File:A3Cnormal (CardioNetworks ECGpedia).avi.webm", 3),
    ],
    "apical_4c": [("File:A4C normal (CardioNetworks ECHOpedia).webm", 1)],
    "suprasternal_arch": [("File:SuprasternalNormal (CardioNetworks ECHOpedia).webm", 1)],
}


def safe_name(title: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", title.split(":", 1)[1])[:120]


def strip_html(text: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", text or "")).strip()


def duration_ms(path: str) -> int:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                         capture_output=True, text=True, check=True)
    return int(round(float(out.stdout.strip()) * 1000))


def qt_ms(rr_ms: float) -> int:
    """End-systole delay after the R-wave, estimated from QT ≈ 0.39 s · √(RR in s)."""
    return int(round(390 * math.sqrt(rr_ms / 1000.0)))


def convert(view_id: str, sources: list[str], out_path: str) -> None:
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y"]
    for src in sources:
        cmd += ["-i", src]
    chains = "".join(f"[{i}:v]scale=720:-2,setsar=1,format=yuv420p[v{i}];" for i in range(len(sources)))
    if len(sources) > 1:
        graph = chains + "".join(f"[v{i}]" for i in range(len(sources))) + f"concat=n={len(sources)}:v=1:a=0[out]"
    else:
        graph = chains.rstrip(";").replace("[v0]", "[out]")
    cmd += ["-filter_complex", graph, "-map", "[out]", "-c:v", "libx264", "-crf", "24", "-pix_fmt", "yuv420p",
            "-an", "-movflags", "+faststart", "-map_metadata", "-1", out_path]
    subprocess.run(cmd, check=True)


def write_attribution(views: dict) -> None:
    """Credits for every bundled real clip (required by CC BY / CC BY-SA)."""
    lines = [
        "EchoScope – cine-loop sources",
        "=============================",
        "",
        "Real echocardiography clips (Wikimedia Commons). They were scaled to 720 px width and",
        "re-encoded (H.264, no audio) without other changes; the converted files are shared",
        "under the same licence as the originals.",
        "",
    ]
    for view_id, view in views.items():
        src = view.get("videoSource", {})
        if src.get("type") == "real":
            lines += [
                f"loops/{view_id}.mp4",
                f"  Source : {src.get('title', '')}",
                f"  Author : {src.get('author', '')}",
                f"  Licence: {src.get('license', '')}  {src.get('licenseUrl', '')}",
                f"  URL    : {src.get('sourceUrl', '')}",
                "",
            ]
    simulated = [v for v, view in views.items() if view.get("videoSource", {}).get("type") != "real"]
    lines += ["Simulated loops (generated by scripts/simulate_loops.py, no patient data):"]
    lines += [f"  loops/{v}.mp4" for v in simulated]
    with open(os.path.join(LOOPS, "ATTRIBUTION.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def main() -> None:
    with open(os.path.join(TEMP, "candidates.json"), encoding="utf-8") as f:
        candidates = json.load(f)
    with open(DB, encoding="utf-8") as f:
        db = json.load(f)
    views = {v["id"]: v for w in db["windows"] for v in w["views"]}

    done = []
    for view_id, clips in MAPPING.items():
        paths = [os.path.join(TEMP, safe_name(title)) for title, _ in clips]
        missing = [p for p in paths if not os.path.exists(p)]
        if missing:
            print(f"skip {view_id}: not downloaded yet ({', '.join(os.path.basename(m) for m in missing)})")
            continue

        r_waves, offset = [], 0
        for (title, beats), path in zip(clips, paths):
            length = duration_ms(path)
            rr = length / beats
            r_waves += [int(round(offset + k * rr)) for k in range(beats)]
            offset += length
        first_rr = (r_waves[1] - r_waves[0]) if len(r_waves) > 1 else offset
        out = os.path.join(LOOPS, f"{view_id}.mp4")
        convert(view_id, paths, out)

        infos = [candidates[title]["imageinfo"][0] for title, _ in clips]
        metas = [i.get("extmetadata", {}) for i in infos]
        authors = sorted({strip_html(m.get("Artist", {}).get("value", "")) for m in metas} - {""})
        licenses = sorted({m.get("LicenseShortName", {}).get("value", "") for m in metas} - {""})
        view = views[view_id]
        view["videoSource"] = {
            "type": "real",
            "title": " + ".join(t.split(":", 1)[1] for t, _ in clips),
            "author": "; ".join(authors) or "CardioNetworks ECHOpedia",
            "license": " / ".join(licenses),
            "licenseUrl": metas[0].get("LicenseUrl", {}).get("value", ""),
            "sourceUrl": " ".join(i.get("descriptionurl", "") for i in infos),
        }
        view["ecg"] = {
            "beatMs": first_rr,
            "edMs": 0,
            "esMs": qt_ms(first_rr),
            "rWavesMs": r_waves if len(r_waves) > 1 else [],
        }
        done.append(view_id)
        print(f"real  {view_id}: {len(clips)} clip(s), {offset} ms, R-waves {r_waves} -> {os.path.relpath(out, ROOT)}")

    with open(DB, "w", encoding="utf-8") as f:
        json.dump(db, f, ensure_ascii=False, indent=2)
        f.write("\n")
    write_attribution(views)
    simulated = [v for v in views if v not in done]
    print(f"\n{len(done)} view(s) now use real clips: {', '.join(done) or '-'}")
    print(f"{len(simulated)} view(s) keep simulated loops: {', '.join(simulated)}")


if __name__ == "__main__":
    main()
